async def generate_response(user_message: str, persona: str = "default", history: list = None):
    """
    Sends a message to the local LM Studio API and returns the AI's text response.
    """
    if history is None:
        history = []

    # Get the system prompt (fallback to default if not found)
    system_prompt = PERSONALITIES.get(persona.lower(), PERSONALITIES["default"])

    # Construct the message payload (System Prompt -> History -> New Message)
    messages = [{"role": "system", "content": system_prompt}]
    messages.extend(history)
    messages.append({"role": "user", "content": user_message})

    payload = {
        "model": "local-model", # LM Studio ignores this, but the OpenAI format requires it
        "messages": messages,
        "temperature": 0.7,
        "max_tokens": 1000,
        "stream": False
    }

    try:
        async with aiohttp.ClientSession() as session:
            async with session.post(LM_STUDIO_URL, json=payload) as response:
                if response.status == 200:
                    data = await response.json()
                    # Return the actual text generated by the AI
                    return data["choices"][0]["message"]["content"]
                else:
                    return f"[API Error: LM Studio returned HTTP status {response.status}. Is the local server started?]"
    except aiohttp.ClientConnectorError:
        return "[Connection Error: Could not connect to LM Studio. Make sure the Local Server is running on port 1234!]"
    except Exception as e:
        return f"[Unexpected AI Error: {e}]"